"""Admit and launch the Codex CLI, including through a batch launcher.

``prepare_codex_launch`` re-admits the executable for each launch and pins
``cmd.exe`` for a batch file without Popen re-quoting ``/c``;
``run_inventory`` runs a bounded, provider-free probe such as
``codex features list``. The no-shell worker launches only native
executables (``noshell.py``); a launcher's batch policy remains for fixed
probes.
"""

from __future__ import annotations

import os
import re
import subprocess
from collections.abc import Callable, Mapping, Sequence

from ..executable_resolution import (
    UnsafeExecutable, admit_executable, prepare_launch, safe_child_env, system_executable,
)
from ..procutil import run_worker
from .base import no_window_kwargs

# A probe such as `codex features list` reads configuration only; it starts no
# server and makes no model call. Bounded so a wedged CLI cannot hold a launch.
INVENTORY_TIMEOUT_SECONDS = 30

InventoryRunner = Callable[[Sequence[str], str, Mapping[str, str]], subprocess.CompletedProcess]


class UnsafeBatchArgument(Exception):
    """Only an argument's role survives a batch-policy refusal."""

    def __init__(self, role: str) -> None:
        self.role = role
        super().__init__(role)


def check_batch_argument(value: str, role: str) -> None:
    # The only quoted values generated by the executor are these TOML literals.
    fixed = role in {"config", "argument"} and value in {'sandbox_mode="read-only"', 'web_search="disabled"'}
    if not fixed and re.fullmatch(r"[A-Za-z0-9._:/=@+\-]{1,200}", value, re.ASCII) is None:
        raise UnsafeBatchArgument(role)


def reject_worker_directory(candidate: str, cwd: str) -> None:
    """Exclude the direct working folder, including links, not its descendants."""
    working = os.path.normcase(os.path.realpath(cwd))
    if working in {
        os.path.normcase(os.path.realpath(os.path.dirname(candidate))),
        os.path.normcase(os.path.dirname(os.path.realpath(candidate))),
    }:
        raise UnsafeExecutable("excluded_cwd")


def prepare_codex_launch(argv: Sequence[str], cwd: str) -> tuple[list[str] | str, dict[str, str]]:
    """Re-admit, then pin cmd for batch files without Popen re-quoting /c.

    The outer payload quotes are consumed by cmd /s. list2cmdline preserves
    the embedded TOML quotes through the npm shim's %* to the native child.
    A string goes unchanged through run_with_tree_kill to Windows Popen;
    executable pins CreateProcess to the same OS-derived command processor.
    """
    if not argv:
        raise UnsafeExecutable("empty_argv")
    reject_worker_directory(argv[0], cwd)
    prepared = prepare_launch(argv, allow_batch=True)
    admitted = admit_executable(prepared[0], allow_batch=True)
    if admitted.path is None:
        raise UnsafeExecutable(admitted.refusal or "not_found")
    if admitted.kind != "batch":
        return prepared, {}
    shim = admitted.path
    if any(char in shim for char in '%!&|<>^'):
        raise UnsafeBatchArgument("executable")
    for index, value in enumerate(prepared[1:], 1):
        previous = prepared[index - 1]
        role = ("model" if previous == "-m" else
                "config" if previous == "-c" else "argument")
        check_batch_argument(value, role)
    command = system_executable("cmd")
    if command.path is None:
        raise UnsafeExecutable(command.refusal or "not_found")
    payload = '"' + '"' + shim + '" ' + subprocess.list2cmdline(prepared[1:]) + '"'
    return '"' + command.path + '" /d /v:off /s /c ' + payload, {"executable": command.path}


def run_inventory(argv: Sequence[str], cwd: str, env: Mapping[str, str]) -> subprocess.CompletedProcess:
    launch, launch_kwargs = prepare_codex_launch(argv, cwd)
    return run_worker(
        launch, cwd=cwd, capture_output=True, text=True, encoding="utf-8",
        errors="replace", timeout=INVENTORY_TIMEOUT_SECONDS, shell=False, env=safe_child_env(env),
        **no_window_kwargs(),
        **launch_kwargs,
    )
